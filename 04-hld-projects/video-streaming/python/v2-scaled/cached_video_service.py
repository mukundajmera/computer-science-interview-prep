from typing import Protocol


class ProcessingOrchestrator(Protocol):
    def enqueue_variant_jobs(self, video_id: str) -> None: ...
    def mark_variant_ready(self, video_id: str, variant: str) -> None: ...
    def mark_failed(self, video_id: str, reason: str) -> None: ...


class UploadPartRegistry(Protocol):
    def record_part(self, session_id: str, part_number: int, etag: str) -> None: ...
    def has_all_parts(self, session_id: str, expected_parts: int) -> bool: ...


class ManifestReadinessStore(Protocol):
    def get_state(self, video_id: str) -> str: ...
    def set_state(self, video_id: str, state: str) -> None: ...
